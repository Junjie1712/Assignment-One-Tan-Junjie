# Task 2: Interactive Keyword Bot
# ============================================================

def run_bot() -> None:
    print("\n" + "=" * 45)
    print("       Interactive Keyword Bot")
    print("Type your question (or 'quit' to exit)")
    print("=" * 45)

    while True:
        # 1. Use input() to receive questions
        user_input = input("\nYou: ").strip().lower()

        if user_input in ("quit", "exit", "bye"):
            print("Bot: Goodbye! Returning to main menu...")
            break

        # 2. Use if/elif/else for logic
        # 3 & 4. Support the required keywords: hello, python, jetson, ai, name
        if "hello" in user_input:
            print("Bot: Hello! Nice to meet you.")

        elif "python" in user_input:
            print("Bot: Python is a powerful and easy-to-learn programming language!")

        elif "jetson" in user_input:
            print("Bot: NVIDIA Jetson is a series of embedded AI computing boards.")

        elif "ai" in user_input:
            print("Bot: AI stands for Artificial Intelligence — machines that can learn and make decisions.")

        elif "name" in user_input:
            print("Bot: My name is KeywordBot. What's yours?")

        else:
            print("Bot: Sorry, I don't understand. Try asking about: hello, python, jetson, ai, or name.")


