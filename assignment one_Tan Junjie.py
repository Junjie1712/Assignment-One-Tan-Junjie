# Main Menu
# ============================================================

def main() -> None:
    while True:
        print("\n" + "=" * 45)
        print("       Assignment One - Menu")
        print("=" * 45)
        print("1. Run Calculator")
        print("2. Run Interactive Keyword Bot")
        print("3. Exit")
        print("=" * 45)

        choice = input("Enter your choice (1/2/3): ").strip()

        if choice == "1":
            run_calculator()
        elif choice == "2":
            run_bot()
        elif choice == "3":
            print("\nGoodbye! Thank you for using the program.")
            break
        else:
            print("Invalid choice. Please enter 1, 2, or 3.")


if __name__ == "__main__":
    main()