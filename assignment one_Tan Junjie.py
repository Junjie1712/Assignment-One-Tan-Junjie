# Task 1: Terminal-based Calculator
# ============================================================

def get_number(prompt: str) -> float:
    """Prompt until a valid number is entered."""
    while True:
        try:
            value = input(prompt).strip()
            return float(value)
        except ValueError:
            print("  Invalid input. Please enter a number (e.g. 5 or 3.14).")


def get_operator() -> str:
    """Prompt until a valid operator is chosen."""
    valid = {"+", "-", "*", "/"}
    while True:
        op = input("Choose operator (+, -, *, /): ").strip()
        if op in valid:
            return op
        print("  Invalid operator. Please enter one of: +  -  *  /")


def calculate(a: float, b: float, op: str) -> float | None:
    """Perform the calculation. Returns None on division by zero."""
    if op == "+":
        return a + b
    if op == "-":
        return a - b
    if op == "*":
        return a * b
    if op == "/":
        if b == 0:
            return None
        return a / b
    return None


def format_number(n: float) -> str:
    """Show integers without trailing .0 for cleaner output."""
    if n == int(n):
        return str(int(n))
    return str(n)


def run_calculator() -> None:
    print("\n" + "=" * 40)
    print("       Simple Terminal Calculator")
    print("=" * 40)

    while True:
        print()
        # 1. Prompt for first number
        num1 = get_number("Enter first number: ")

        # 2. Prompt for second number
        num2 = get_number("Enter second number: ")

        # 3. Choose operator
        operator = get_operator()

        # Perform calculation
        result = calculate(num1, num2, operator)

        # 4. Display clear math result
        print()
        if result is None:
            print("Error: Division by zero is not allowed.")
        else:
            a = format_number(num1)
            b = format_number(num2)
            r = format_number(result)
            print(f"Result:  {a} {operator} {b} = {r}")

        # Ask to continue
        print()
        again = input("Do another calculation? (y/n): ").strip().lower()
        if again not in ("y", "yes"):
            print("\nReturning to main menu...")
            break


